"""Teste de regressão do World Studio v2.3. Requer Playwright e Chromium."""
from pathlib import Path
from playwright.sync_api import sync_playwright
INDEX = Path(__file__).resolve().parents[1] / "index.html"
tests = []
def check(label, ok):
    tests.append(bool(ok))
    print(("OK " if ok else "FALHA ") + label)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path="/usr/bin/chromium", args=["--no-sandbox"])
    page = browser.new_page(viewport={"width": 1600, "height": 960}, accept_downloads=True)
    errors = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.goto("about:blank")
    page.evaluate("""(()=>{const s=new Map();Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>s.get(k)||null,setItem:(k,v)=>s.set(k,String(v)),removeItem:k=>s.delete(k)}})})()""")
    page.set_content(INDEX.read_text(encoding="utf-8"))
    page.locator("#wmkOpenMapStudio").click()
    page.locator("#studioMapSelect").select_option("terminal-zero")
    check("Editor aberto", page.locator("#wmkMapStudio").is_visible())
    check("Arvore de entidades", page.locator("#studioHierarchy [role=treeitem]").count() > 20)
    check("Camadas listadas", page.locator("#studioLayers .studio-layer-row").count() > 1)
    page.evaluate("""()=>{const a=editingMap.objects.slice(0,2);a[0].x=700;a[0].y=900;a[0].w=100;a[0].h=60;a[0].layer=8;a[1].x=900;a[1].y=900;a[1].w=100;a[1].h=60;a[1].layer=8;studioSetSelection(a.map(o=>'obj:'+o.id))}""")
    check("Multisselecao", page.evaluate("studioEditableEntries().length") == 2)
    page.locator("#studioGroup").click()
    check("Grupo criado", page.evaluate("selectedStudioEntries().every(e=>!!e.entity.groupId)"))
    check("Pivo central", page.evaluate("Math.round(studioPivot().x)") == 800)
    page.locator("#studioPivotMode").select_option("active")
    check("Pivo ativo", page.evaluate("Math.round(studioPivot().x)") == 900)
    page.locator("#studioPivotMode").select_option("center")
    page.locator("#studioTool").select_option("select")
    def handle_pos(kind):
        return page.evaluate("""kind=>{const g=gizmoGeometry(),t=drawingTransform(),r=studioCanvas.getBoundingClientRect(),v=g[kind];return {x:r.left+(v.x*t.scale+t.ox)*r.width/studioCanvas.width,y:r.top+(v.y*t.scale+t.oy)*r.height/studioCanvas.height}}""", kind)
    page.locator("#gizmoScale").click()
    initial = page.evaluate("selectedStudioEntries().map(e=>e.entity.w)")
    pos = handle_pos("scale")
    page.mouse.move(pos["x"],pos["y"]);page.mouse.down()
    page.mouse.move(pos["x"]+35,pos["y"]+22,steps=10);page.mouse.up()
    check("Escala coletiva", all(a>b for a,b in zip(page.evaluate("selectedStudioEntries().map(e=>e.entity.w)"),initial)))
    page.locator("#gizmoRotate").click()
    pos = handle_pos("rotate")
    page.mouse.move(pos["x"],pos["y"]);page.mouse.down()
    page.mouse.move(pos["x"]+80,pos["y"]+30,steps=10);page.mouse.up()
    check("Rotacao coletiva", page.evaluate("selectedStudioEntries().every(e=>e.entity.rotation!==0)"))
    page.locator("#studioUndo").click()
    check("Undo da rotacao", page.evaluate("editingMap.objects.some(o=>o.layer===8&&o.rotation===0)"))
    page.locator("#studioRedo").click()
    check("Redo da rotacao", page.evaluate("editingMap.objects.some(o=>o.layer===8&&o.rotation!==0)"))
    page.locator('#studioLayers [aria-label="Alternar bloqueio da camada 8"]').click()
    check("Bloqueio de camada", page.evaluate("studioLayerOptions(8).locked"))
    check("Bloqueados nao editaveis", page.evaluate("studioEditableEntries().length")==0)
    page.locator('#studioLayers [aria-label="Alternar bloqueio da camada 8"]').click()
    page.locator('#studioLayers [aria-label="Alternar visibilidade da camada 8"]').click()
    check("Ocultacao de camada", page.evaluate("studioLayerOptions(8).visible") is False)
    page.locator('#studioLayers [aria-label="Alternar visibilidade da camada 8"]').click()
    page.locator("#studioSave").click()
    check("Persistencia simulada", page.evaluate("""()=>JSON.parse(localStorage.getItem('wmk-world-studio-maps-v1')).find(m=>m.id==='terminal-zero').layerSettings['8'].visible"""))
    with page.expect_download() as d: page.locator("#studioExport").click()
    check("Exportacao JSON", d.value.suggested_filename.endswith(".json"))
    check("Sem excecoes JavaScript", not errors)
    browser.close()
print(f"APROVADOS: {sum(tests)}/{len(tests)}")
assert all(tests)
