"""Teste de integração WMK v1.6: abrir editores e validar os catálogos."""
from pathlib import Path
from playwright.sync_api import sync_playwright
P=Path(__file__).resolve().parents[1]/"index.html"
checks=[]
def ck(name,val):
 checks.append(bool(val));print(("OK" if val else "FALHA")+" "+name)
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True)
 page=browser.new_page(viewport={"width":1500,"height":900},accept_downloads=True)
 errors=[];page.on("pageerror",lambda e:errors.append(str(e)))
 page.goto("about:blank")
 page.evaluate("(()=>{const m=new Map();Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>m.get(k)||null,setItem:(k,v)=>m.set(k,v),removeItem:k=>m.delete(k)}})})()")
 page.set_content(P.read_text(encoding="utf8"))
 ck("Menu inicial",page.locator("#wmkMain").is_visible())
 ck("Editor de objetos",page.locator("#wmkOpenObjectStudio").count()==1)
 ck("Editor de armas",page.locator("#wmkOpenWeaponStudio").count()==1)
 page.locator("#wmkOpenObjectStudio").click()
 ck("Object Lab abre",page.locator("#wmkObjectStudio").is_visible())
 ck("Biblioteca inicial",page.locator("#objectList option").count()>=3)
 page.locator("#objectNew").click()
 page.locator("#prefName").fill("Parede teste")
 page.locator("#prefW").fill("205")
 page.locator("#prefSolid").check()
 page.locator("#objectForm button[type=submit]").click()
 ck("Objeto foi salvo",page.evaluate("objectCatalog.some(o=>o.name==='Parede teste'&&o.w===205&&o.solid)"))
 page.locator("#objectClone").click()
 ck("Duplicar objeto",page.locator("#objectList option").count()>=5)
 with page.expect_download() as d:page.locator("#objectExport").click()
 ck("Exportar objetos",d.value.suggested_filename.endswith(".json"))
 page.locator("#objectReturn").click()
 page.locator("#wmkOpenWeaponStudio").click()
 ck("Arsenal Lab abre",page.locator("#wmkWeaponStudio").is_visible())
 page.locator("#weaponNew").click()
 page.locator("#wpName").fill("Arma teste")
 page.locator("#wpDamage").fill("13")
 page.locator("#wpRate").fill("3.2")
 page.locator("#weaponForm button[type=submit]").click()
 wid=page.evaluate("weaponCatalog.find(w=>w.name==='Arma teste').id")
 ck("Arma foi salva",bool(wid))
 ck("Cadência foi salva",page.evaluate("weaponById("+repr(wid)+").rate")==3.2)
 with page.expect_download() as d:page.locator("#weaponExport").click()
 ck("Exportar armas",d.value.suggested_filename.endswith(".json"))
 page.locator("#weaponReturn").click()
 page.locator("#wmkOpenBotStudio").click()
 ck("Arma disponível no Bot Lab",page.locator("#botWeapon option[value='"+wid+"']").count()==1)
 page.locator("#botMap").select_option("terminal-zero")
 page.locator("#botWeapon").select_option(wid)
 ck("Dano do bot atualizado",page.locator("#botDamage").input_value()=="13")
 page.locator("#botForm button[type=submit]").click()
 ck("Arma vinculada ao bot",page.evaluate("botSelected().weapon")==wid)
 page.locator("#botReturn").click()
 page.locator("#wmkOpenMapStudio").click()
 page.locator("#studioMapSelect").select_option("terminal-zero")
 page.locator("#studioTool").select_option("prefab")
 page.locator("#studioPrefabSelect").select_option(page.evaluate("objectCatalog.find(o=>o.name==='Parede teste').id"))
 page.locator("#studioCanvas").click(position={"x":500,"y":340})
 ck("Prefab inserido",page.evaluate("selectedObject()?.name==='Parede teste'"))
 page.locator("#studioTool").select_option("bot")
 ck("Janela de modelos aparece",page.locator("#wmkBotPicker").is_visible())
 ck("Equipes visíveis",page.locator("#pickerCards .red").count()>0 and page.locator("#pickerCards .blue").count()>0 and page.locator("#pickerCards .neutral").count()>0)
 page.locator("#pickerCards .blue").first.click()
 page.locator("#studioCanvas").click(position={"x":590,"y":400})
 ck("Bot aliado inserido",page.evaluate("selectedBotInMap()?.team==='blue'"))
 ck("Sem exceções JavaScript",not errors)
 browser.close()
print(f"{sum(checks)}/{len(checks)} aprovados")
raise SystemExit(0 if all(checks) else 1)
