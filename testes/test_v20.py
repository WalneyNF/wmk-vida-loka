from pathlib import Path
from playwright.sync_api import sync_playwright
p=Path(__file__).resolve().parents[1]
checks=[]
def check(name,ok):
    checks.append((name,bool(ok)))
    print(('OK ' if ok else 'FALHA ')+name)
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1480,'height':900},accept_downloads=True)
    errors=[]
    page.on('pageerror',lambda err:errors.append(str(err)))
    page.set_content((p/'index.html').read_text(encoding='utf8'),wait_until='load')
    check('Menu inicial',page.locator('#wmkMain').is_visible())
    page.locator('#wmkOpenAvatarStudio').click()
    page.locator('#avatarName').fill('Lince Azul')
    page.locator('#avatarProfileSave').click()
    check('Perfil salvo',page.evaluate("avatarProfiles.length===1"))
    page.locator('#avatarReset').click()
    page.locator('#avatarProfileLoad').click()
    check('Perfil recuperado',page.locator('#avatarName').input_value()=='Lince Azul')
    page.locator('#avatarReturn').click()
    page.locator('#wmkOpenBotStudio').click()
    check('Editor de bots',page.locator('#wmkBotStudio').is_visible())
    check('Avatares visíveis para bots',page.locator('#botAvatar option').count()==2)
    page.locator('#botMap').select_option('terminal-zero')
    page.locator('#botList').select_option('guard-1')
    page.locator('#botAvatar').select_option(page.evaluate('avatarProfiles[0].id'))
    page.locator('#botForm button[type=submit]').click()
    check('Bot com avatar',page.evaluate("mapCatalog.find(m=>m.id==='terminal-zero').bots[0].avatarId===avatarProfiles[0].id"))
    page.locator('#botReturn').click()
    page.locator('#wmkOpenMissionStudio').click()
    page.locator('#missionFlow').click()
    check('Fluxo da missão',page.locator('#missionFlowView').is_visible())
    page.locator('#missionReturn').click()
    page.locator('#wmkOpenMapStudio').click()
    page.locator('#studioMapSelect').select_option('terminal-zero')
    page.locator('#studioDebugCollision').check()
    check('Depuração de colisões',page.locator('#studioDebugCollision').is_checked())
    count=page.evaluate('editingMap.objects.length')
    page.locator('#studioTool').select_option('terrain')
    page.locator('#studioCanvas').click(position={'x':430,'y':350})
    check('Pincel de terreno',page.evaluate('editingMap.objects.length')==count+1)
    page.locator('#studioTool').select_option('select')
    page.evaluate("setStudioSelection(editingMap.bots[0],'bot')")
    page.locator('#studioTool').select_option('patrol')
    before=page.evaluate('editingMap.bots[0].patrol.length')
    page.locator('#studioCanvas').click(position={'x':530,'y':380})
    check('Waypoint inserido',page.evaluate('editingMap.bots[0].patrol.length')==before+1)
    check('A* encontra rota',bool(page.evaluate('botRouteAStar({x:230,y:300},{x:2340,y:1800})')))
    page.locator('#studioReturn').click()
    page.locator('#wmkOpenGameCreator').click()
    check('Game Creator abre',page.locator('#wmkGameCreator').is_visible())
    check('Quatro mapas disponíveis',page.locator('#creatorMaps input').count()>=4)
    check('Pacote válido',page.evaluate("buildCreatorPackage().format==='wmk-game-package'"))
    with page.expect_download() as download:
        page.locator('#creatorExport').click()
    check('Exportação JSON',download.value.suggested_filename.endswith('.json'))
    page.locator('#creatorReturn').click()
    check('Retorno ao menu',page.locator('#wmkMain').is_visible())
    page.locator('#wmkPlay').click()
    check('Jogo inicia',page.evaluate("wmkMode==='play'"))
    page.wait_for_timeout(800)
    check('Modo ativo',page.evaluate("wmkMode==='play' && !!currentMap"))
    check('Sem exceções JS',not errors)
    browser.close()
print(f'{sum(v for _,v in checks)}/{len(checks)} testes')
assert all(v for _,v in checks)
